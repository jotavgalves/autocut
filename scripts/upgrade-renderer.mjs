import fs from "node:fs";
const file = "src/renderer/app.js";
let source = fs.readFileSync(file, "utf8");
const broken = "S.margin.transparent?.12:Math.max(.08,Math.min(.55,(S.margin.opacity??1)*.35))";
const fixed = "S.margin.transparent ? .12 : Math.max(.08,Math.min(.55,(S.margin.opacity??1)*.35))";
if (!source.includes(broken)) throw new Error("A assinatura da falha de sintaxe esperada não foi encontrada; nenhuma alteração foi feita.");
source = source.replace(broken, fixed);
if (source.includes("transparent?.12")) throw new Error("A correção não removeu completamente a expressão inválida.");
fs.writeFileSync(file, source);
console.log("Renderer final corrigido.");
